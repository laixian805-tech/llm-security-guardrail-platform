def test_postgres_ddl_generation_and_sqlalchemy_fail_closed(tmp_path):
    ddl = generate_postgres_ddl()
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "AUTOINCREMENT" not in ddl
    assert f"VALUES ('schema_version', '{SCHEMA_VERSION}')" in ddl

    if not has_postgres_driver():
        with pytest.raises(RuntimeError, match="postgres_driver_missing"):
            create_sqlalchemy_engine("postgresql://user:pass@localhost:5432/asgp")

    from storage.repositories import Storage
    db = tmp_path / "sa.db"
    Storage(db)
    info = check_sqlite_schema_via_sqlalchemy(db)
    assert info["dialect"] == "sqlite"
    assert info["schema_version"] == str(SCHEMA_VERSION)
    assert info["table_count"] >= 28


def test_notification_hub_sse_ssrf_async_ingest_and_push_approval(api, admin_token):
    # SSRF guard blocks localhost unless explicit opt-in
    assert not _is_safe_webhook_url("http://127.0.0.1:9999/hook")
    assert not _is_safe_webhook_url("ftp://example.com/hook")

    # /api/health reports storage_dialect & async_ingest stats
    health = call(api.base, "GET", "/api/health", token=admin_token).json()
    assert health["storage_dialect"] == "sqlite"
    assert "async_ingest" in health

    # Enroll + bind device
    from test_v1_ingest import setup_device
    dev = setup_device(api, admin_token, "p2-push-dev")

    # SSE one-shot endpoint emits ready frame
    parsed = urlparse(api.base)
    conn = http.client.HTTPConnection(parsed.hostname, parsed.port, timeout=5)
    conn.request("GET", "/api/v1/events/stream?once=1", headers={"Authorization": f"Bearer {admin_token}"})
    resp = conn.getresponse()
    body = resp.read().decode("utf-8")
    conn.close()
    assert resp.status == 200
    assert "text/event-stream" in resp.getheader("Content-Type", "")
    assert "event: ready" in body

    # Async batch ingest returns 202 and persists event asynchronously
    async_res = call(
        api.base,
        "POST",
        "/api/v1/runtime-events:ingest-async",
        token=dev["token"],
        body={
            "collector_id": "linux-audit-v1",
            "events": [{
                "event_id": "ev_async_p2_1",
                "event_type": "network_connect",
                "occurred_at": "2026-11-14T12:00:00+00:00",
                "action": "sendto",
                "result": "success",
                "resource": {"host": "webhook.site", "port": 443},
            }],
        },
    )
    assert async_res.status_code == 202
    assert async_res.json()["accepted"] is True

    found = False
    for _ in range(30):
        evs = call(api.base, "GET", f"/api/v1/runtime-events?host_id=host_p2-push-dev", token=admin_token).json()["events"]
        if any(e["event_id"] == "ev_async_p2_1" for e in evs):
            found = True
            break
        time.sleep(0.05)
    assert found

    # Push-wait approval unblocks quickly on resolve
    cfg = {"server_base_url": api.base, "device_token": dev["token"], "approval_timeout_seconds": 5, "approval_push_wait": True}
    ev = {"session_id": "s-push", "tool_call_id": "c-push", "tool_name": "Bash", "params": {"command": "echo PUSH"}}
    out = []
    t = threading.Thread(target=lambda: out.append(request_approval(cfg, "codex", "0.166.0", ev)))
    t.start()
    rows = []
    for _ in range(30):
        rows = call(api.base, "GET", "/api/v1/approvals", token=admin_token).json()["approvals"]
        if rows:
            break
        time.sleep(0.05)
    assert rows
    row = rows[0]
    call(api.base, "POST", f"/api/v1/approvals/{row['approval_id']}", token=admin_token,
         body={"decision": "approved", "params_sha256": row["params_sha256"]}).raise_for_status()
    t.join(timeout=5)
    assert not t.is_alive() and out[0][0] == "allow"
