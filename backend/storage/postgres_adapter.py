"""PostgreSQL 存储方言转换、Schema 对等校验与 SQLAlchemy 引擎抽象。

ASGP 控制面默认用 SQLite (`data/fusion.db`) 保持单机零外部运维成本；当切换至
多设备/高并发环境时，可通过本模块生成与 `storage/schema.py`（SCHEMA_VERSION）
严格对等的 PostgreSQL DDL，并经 SQLAlchemy 创建统一数据库引擎。若运行环境
尚未安装 psycopg/psycopg2 驱动，PostgreSQL 连接会显式 fail-closed 报错，
绝不静默回退到本地 SQLite。
"""

from __future__ import annotations

import importlib.util
from pathlib import Path
from typing import Any

from sqlalchemy import create_engine, text
from sqlalchemy.engine import Engine

from storage.schema import DDL, INDEX_DDL, SCHEMA_VERSION


_PG_MIGRATION_PATCHES = """
ALTER TABLE detector_runs ADD COLUMN IF NOT EXISTS provider_profile_id TEXT;
ALTER TABLE detector_runs ADD COLUMN IF NOT EXISTS model_id TEXT;
ALTER TABLE detector_runs ADD COLUMN IF NOT EXISTS wire_api TEXT;
ALTER TABLE detector_runs ADD COLUMN IF NOT EXISTS latency_ms INTEGER;
ALTER TABLE admissions ADD COLUMN IF NOT EXISTS product_id TEXT;
ALTER TABLE admissions ADD COLUMN IF NOT EXISTS product_target TEXT;
ALTER TABLE admissions ADD COLUMN IF NOT EXISTS product_rollback_ref TEXT;
ALTER TABLE admissions ADD COLUMN IF NOT EXISTS product_loaded INTEGER;
ALTER TABLE admissions ADD COLUMN IF NOT EXISTS product_verification TEXT;
ALTER TABLE governance_transitions ADD COLUMN IF NOT EXISTS detail TEXT;
ALTER TABLE executions ADD COLUMN IF NOT EXISTS product_version_source TEXT NOT NULL DEFAULT 'device_claim';
ALTER TABLE asset_releases ADD COLUMN IF NOT EXISTS publisher_id TEXT REFERENCES publishers(publisher_id);
ALTER TABLE asset_releases ADD COLUMN IF NOT EXISTS signature TEXT;
ALTER TABLE asset_releases ADD COLUMN IF NOT EXISTS verified_at TEXT;
INSERT INTO schema_meta (key, value) VALUES ('schema_version', '__SCHEMA_VERSION__')
ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
""".strip()


def generate_postgres_ddl() -> str:
    """将当前 `SCHEMA_VERSION` 的 SQLite 契约映射为幂等可执行的 PostgreSQL DDL。"""
    pg_ddl = DDL.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    )
    parts = [
        "-- Auto-generated from backend/storage/schema.py",
        pg_ddl.strip(),
        INDEX_DDL.strip(),
        _PG_MIGRATION_PATCHES.replace("__SCHEMA_VERSION__", str(SCHEMA_VERSION)),
    ]
    return "\n\n".join(parts) + "\n"


def has_postgres_driver() -> bool:
    return any(
        importlib.util.find_spec(mod) is not None
        for mod in ("psycopg", "psycopg2", "pg8000")
    )


def create_sqlalchemy_engine(db_url: str) -> Engine:
    """根据连接串构建 SQLAlchemy Engine；PostgreSQL 无驱动时显式报错。"""
    normalized = (db_url or "").strip()
    if normalized.startswith(("postgres://", "postgresql://", "postgresql+")):
        if normalized.startswith("postgres://"):
            normalized = "postgresql://" + normalized[len("postgres://"):]
        if not has_postgres_driver():
            raise RuntimeError("postgres_driver_missing: install psycopg or psycopg2")
        return create_engine(normalized, pool_pre_ping=True, future=True)
    if normalized.startswith("sqlite:///") or normalized == "sqlite:///:memory:":
        return create_engine(normalized, future=True)
    # 兼容直接传入文件路径
    path = Path(normalized).resolve()
    return create_engine(f"sqlite:///{path}", future=True)


def check_sqlite_schema_via_sqlalchemy(db_path: Path | str) -> dict[str, Any]:
    """用 SQLAlchemy 查询 SQLite 元信息，验证双引擎抽象层健康度。"""
    engine = create_sqlalchemy_engine(str(db_path))
    try:
        with engine.connect() as conn:
            tables = [
                row[0]
                for row in conn.execute(
                    text("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name")
                ).fetchall()
            ]
            row = conn.execute(
                text("SELECT value FROM schema_meta WHERE key = 'schema_version'")
            ).fetchone()
            return {
                "dialect": engine.dialect.name,
                "schema_version": row[0] if row else None,
                "table_count": len(tables),
                "tables": tables,
            }
    finally:
        engine.dispose()
